"""Build the IEEE paper from measured evaluation results.

Every number in the paper comes from evaluation/results/<run>/summary.json through the
macros and tables generated here; none are typed by hand.

    python paper/build.py                       # uses evaluation/results/latest
    python paper/build.py --dev-run results/20261101-002519   # also emits the development-iteration table
Then compile:  tectonic paper/main.tex
"""
import argparse
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PROJECT = ROOT.parent
EVAL = PROJECT / "evaluation"
GEN = ROOT / "generated"


def tex_escape(s):
    s = str(s)
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    s = "".join(rep.get(c, c) for c in s)
    return (s.replace("→", r"$\rightarrow$").replace("≥", r"$\geq$").replace("×", r"$\times$")
             .replace("≈", r"$\approx$").replace("–", "--"))


def macro_name(*parts):
    """metric names -> letters-only TeX macro names, e.g. refinement_success_rate,pipeline -> RefinementSuccessRatePipeline"""
    out = ""
    for p in parts:
        for w in re.split(r"[^A-Za-z0-9]+", str(p)):
            w = re.sub(r"\d", lambda m: "ZOTTFFSSEN"[int(m.group())], w)
            out += w[:1].upper() + w[1:]
    return out


def fmt(v, unit=""):
    if v is None:
        return "--"
    if isinstance(v, (int, float)):
        if unit == "ms":
            return f"{v/1000:.1f}"  # seconds in the paper
        if isinstance(v, int) and not isinstance(v, bool):
            return str(v)
        return f"{v:.1f}" if abs(v) >= 1 or v == 0 else f"{v:.2f}"
    return tex_escape(v)


def write_macros(summary, prefix, path):
    lines = [f"% generated by paper/build.py from summary.json ({summary['generated_at']})"]
    for name, m in summary["metrics"].items():
        unit = m.get("unit", "")
        for k, v in m.items():
            if k in ("unit", "description") or isinstance(v, (dict, list)):
                continue
            lines.append(f"\\newcommand{{\\{macro_name(prefix, name, k)}}}{{{fmt(v, unit)}}}")
    c = summary["config"]["counts"]
    for k, v in c.items():
        lines.append(f"\\newcommand{{\\{macro_name(prefix, 'count', k)}}}{{{v}}}")
    run = summary["config"].get("run", {})
    calls = run.get("api_calls_total_in_raw") or {}
    lines.append(f"\\newcommand{{\\{macro_name(prefix, 'api calls')}}}{{{sum(calls.values()) if calls else '--'}}}")
    path.write_text("\n".join(lines) + "\n")


def table_tex(t, label, caption=None, cols=None, wide=False, size="\\scriptsize", fmtcell=None):
    columns = t["columns"]
    idx = list(range(len(columns))) if cols is None else [columns.index(c) for c in cols]
    head = " & ".join(f"\\textbf{{{tex_escape(columns[i])}}}" for i in idx)
    body = []
    for r in t["rows"]:
        cells = []
        for i in idx:
            v = r[i]
            cells.append(fmtcell(columns[i], v) if fmtcell else (tex_escape(v) if not isinstance(v, float) else f"{v:.1f}"))
        body.append(" & ".join(cells) + r" \\")
    env = "table*" if wide else "table"
    align = "l" + "r" * (len(idx) - 1)
    return "\n".join([
        f"\\begin{{{env}}}[t]", "\\centering", size,
        f"\\caption{{{caption if caption else tex_escape(t['title'])}}}", f"\\label{{{label}}}",
        "\\setlength{\\tabcolsep}{3.5pt}",
        f"\\begin{{adjustbox}}{{max width={'\\textwidth' if wide else '\\columnwidth'}}}",
        f"\\begin{{tabular}}{{{align}}}", "\\toprule", head + r" \\", "\\midrule", *body, "\\bottomrule",
        "\\end{tabular}", "\\end{adjustbox}", f"\\end{{{env}}}", ""])


def find(summary, start):
    for t in summary["tables"]:
        if t["title"].startswith(start):
            return t
    raise KeyError(start)


HEADLINE_NAMES = {
    "component_detection_f1": "Component detection F1 (analysis vs.\\ baseline DOM)",
    "component_detection_f1_dom": "Component detection F1 (both on rendered DOM)",
    "whisper_wer": "Whisper word error rate",
    "voice_command_accuracy": "Voice command accuracy (from Whisper)",
    "visual_similarity_layout_iou": "Visual similarity: layout IoU $\\times$100",
    "visual_similarity_edge_ssim": "Visual similarity: edge SSIM $\\times$100",
    "functional_correctness": "Functional correctness",
    "requirement_satisfaction": "Requirement satisfaction",
    "refinement_success_rate": "Refinement success rate",
    "preservation_rate": "Preservation of unaffected components",
    "validation_pass_rate_before_repair": "Validation pass rate before repair",
    "validation_pass_rate_after_repair": "Validation pass rate after repair",
    "fault_detection_rate": "Injected faults detected",
    "fault_repair_rate": "Injected faults repaired",
    "generation_time_ms": "Generation time, mean (s)",
    "modification_time_ms": "Modification time, mean (s)",
    "code_parse_rate": "Generated code parses",
    "code_eslint_messages": "ESLint messages per UI",
    "code_reuse_ratio": "Component reuse ratio",
    "code_max_function_lines": "Longest function (lines)",
}


def headline_table(summary):
    rows = []
    for k, name in HEADLINE_NAMES.items():
        m = summary["metrics"].get(k)
        if not m:
            continue
        unit = m.get("unit", "")
        u = "s" if unit == "ms" else tex_escape(unit)
        rows.append(f"{name} & {fmt(m['pipeline'], unit)} & {fmt(m.get('baseline'), unit)} & {u} \\\\")
    return "\n".join([
        "\\begin{table}[t]", "\\centering", "\\scriptsize",
        "\\caption{Headline results on the same 40 sketches and 80 commands (proposed vs.\\ one-call baseline)}",
        "\\label{tab:headline}", "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{adjustbox}{max width=\\columnwidth}", "\\begin{tabular}{lrrl}", "\\toprule",
        "\\textbf{Metric} & \\textbf{Proposed} & \\textbf{Baseline} & \\textbf{Unit} \\\\", "\\midrule",
        *rows, "\\bottomrule", "\\end{tabular}", "\\end{adjustbox}", "\\end{table}", ""])


def dev_table(dev, final):
    keys = ["component_detection_f1", "component_detection_f1_dom", "visual_similarity_layout_iou",
            "functional_correctness", "refinement_success_rate", "validation_pass_rate_before_repair",
            "validation_pass_rate_after_repair", "fault_repair_rate"]
    rows = []
    for k in keys:
        a, b = dev["metrics"].get(k), final["metrics"].get(k)
        if not a or not b:
            continue
        rows.append(f"{HEADLINE_NAMES[k]} & {fmt(a['pipeline'], a['unit'])} & {fmt(b['pipeline'], b['unit'])} & {fmt(b.get('baseline'), b['unit'])} \\\\")
    return "\n".join([
        "\\begin{table}[t]", "\\centering", "\\scriptsize",
        "\\caption{Development iteration: the first full evaluation exposed pipeline defects that were fixed (Sec.~\\ref{sec:dev}); same test set}",
        "\\label{tab:dev}", "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{adjustbox}{max width=\\columnwidth}", "\\begin{tabular}{lrrr}", "\\toprule",
        "\\textbf{Metric} & \\textbf{Run 1} & \\textbf{Final} & \\textbf{Baseline} \\\\", "\\midrule",
        *rows, "\\bottomrule", "\\end{tabular}", "\\end{adjustbox}", "\\end{table}", ""])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="results/latest", help="evaluation run dir (relative to evaluation/)")
    ap.add_argument("--dev-run", default=None, help="earlier run to report as the development iteration")
    a = ap.parse_args()
    run = EVAL / a.run
    s = json.loads((run / "summary.json").read_text())
    GEN.mkdir(exist_ok=True)
    write_macros(s, "", GEN / "numbers.tex")
    (GEN / "headline.tex").write_text(headline_table(s))

    def num(col, v):
        return f"{v:.1f}" if isinstance(v, float) else tex_escape(v)

    (GEN / "detection.tex").write_text(table_tex(find(s, "Component detection"), "tab:detection",
        "Component detection (micro-averaged; Hungarian matching, IoU $\\geq$ 0.3, correct type)",
        cols=["Detector / output", "Precision %", "Recall %", "F1 %", "Type acc. of matched %", "Mean IoU of matched"],
        wide=True, fmtcell=num))
    (GEN / "detcat.tex").write_text(table_tex(find(s, "Detection F1 % per category"), "tab:detcat", fmtcell=num))
    (GEN / "voice.tex").write_text(table_tex(find(s, "Voice command interpretation"), "tab:voice",
        "Voice command interpretation accuracy (\\%)", fmtcell=num))
    (GEN / "voicecat.tex").write_text(table_tex(find(s, "Voice results per command category"), "tab:voicecat", fmtcell=num))
    (GEN / "quality.tex").write_text(table_tex(find(s, "Generated UI quality"), "tab:quality",
        "Generated UI quality: visual similarity, functional correctness, requirement satisfaction", wide=True, fmtcell=num))
    (GEN / "refine.tex").write_text(table_tex(find(s, "Refinement success"), "tab:refine",
        "Refinement success and preservation (\\%) per command category", wide=True, fmtcell=num))
    (GEN / "repair.tex").write_text(table_tex(find(s, "Validation before vs after"), "tab:repair",
        "Validation before vs.\\ after the repair loop", fmtcell=num))
    (GEN / "faults.tex").write_text(table_tex(find(s, "Fault injection"), "tab:faults",
        "Fault injection: validator detection and repair recovery (\\%)", fmtcell=num))
    (GEN / "latency.tex").write_text(table_tex(find(s, "Latency"), "tab:latency", "Latency per stage (ms)", fmtcell=num))
    (GEN / "code.tex").write_text(table_tex(find(s, "Code quality"), "tab:code",
        "Static code quality of the generated React (mean per UI)", wide=True, fmtcell=num))
    if a.dev_run:
        d = json.loads((EVAL / a.dev_run / "summary.json").read_text())
        (GEN / "dev.tex").write_text(dev_table(d, s))
        write_macros(d, "dev", GEN / "devnumbers.tex")
    else:
        (GEN / "dev.tex").write_text("")
        (GEN / "devnumbers.tex").write_text("")

    figs = ROOT / "figures" / "eval"
    figs.mkdir(parents=True, exist_ok=True)
    for p in (run / "plots").glob("*.pdf"):
        shutil.copy2(p, figs / p.name)
    print("generated:", sorted(x.name for x in GEN.iterdir()), "| plots:", len(list(figs.glob("*.pdf"))))


if __name__ == "__main__":
    main()
